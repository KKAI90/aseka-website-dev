export function dashTime(raw: string, lang: AdminLang): string {
  if (lang === "ja" || !raw) return raw;
  if (raw.startsWith("本日 ")) return (lang === "en" ? "Today " : "Hôm nay ") + raw.slice(3);
  if (raw.startsWith("昨日 ")) return (lang === "en" ? "Yesterday " : "Hôm qua ") + raw.slice(3);
  return raw;
}

type Ctx = { lang: AdminLang; setLang: (l: AdminLang) => void; t: (key: string, vars?: Record<string,string|number>) => string };
const AdminLangContext = createContext<Ctx | null>(null);

export function AdminLangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<AdminLang>("ja");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? window.localStorage.getItem("admin_lang") : null;
    if (saved === "en" || saved === "vi" || saved === "ja") setLangState(saved);
  }, []);

  const setLang = useCallback((l: AdminLang) => {
    setLangState(l);
    if (typeof window !== "undefined") window.localStorage.setItem("admin_lang", l);
  }, []);

  const t = useCallback((key: string, vars?: Record<string,string|number>) => {
    let str = DICT[key]?.[lang] ?? key;
    if (vars) Object.entries(vars).forEach(([k,v]) => { str = str.replace(`{${k}}`, String(v)); });
    return str;
  }, [lang]);

  return <AdminLangContext.Provider value={{ lang, setLang, t }}>{children}</AdminLangContext.Provider>;
}

export function useAdminLang() {
  const ctx = useContext(AdminLangContext);
  if (!ctx) throw new Error("useAdminLang must be used within AdminLangProvider");
  return ctx;
}
